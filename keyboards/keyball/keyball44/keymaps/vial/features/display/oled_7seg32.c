// セグメント定義
#define SEG32_A (1 << 0)
#define SEG32_B (1 << 1)
#define SEG32_C (1 << 2)
#define SEG32_D (1 << 3)
#define SEG32_E (1 << 4)
#define SEG32_F (1 << 5)
#define SEG32_G (1 << 6)

static uint8_t get_seg_mask(char c) {
    switch (c) {
        case '0': return SEG32_A | SEG32_B | SEG32_C | SEG32_D | SEG32_E | SEG32_F;
        case '1': return SEG32_B | SEG32_C;
        case '2': return SEG32_A | SEG32_B | SEG32_G | SEG32_E | SEG32_D;
        case '3': return SEG32_A | SEG32_B | SEG32_G | SEG32_C | SEG32_D;
        case '4': return SEG32_F | SEG32_G | SEG32_B | SEG32_C;
        case '5': return SEG32_A | SEG32_F | SEG32_G | SEG32_C | SEG32_D;
        case '6': return SEG32_A | SEG32_F | SEG32_E | SEG32_D | SEG32_C | SEG32_G;
        case '7': return SEG32_A | SEG32_B | SEG32_C;
        case '8': return SEG32_A | SEG32_B | SEG32_C | SEG32_D | SEG32_E | SEG32_F | SEG32_G;
        case '9': return SEG32_A | SEG32_B | SEG32_C | SEG32_D | SEG32_F | SEG32_G;
        case 'A':
        case 'a': return SEG32_A | SEG32_B | SEG32_C | SEG32_E | SEG32_F | SEG32_G;
        case 'B':
        case 'b': return SEG32_F | SEG32_E | SEG32_G | SEG32_C | SEG32_D;
        case 'C':
        case 'c': return SEG32_A | SEG32_F | SEG32_E | SEG32_D;
        case 'D':
        case 'd': return SEG32_B | SEG32_G | SEG32_E | SEG32_D | SEG32_C;
        case 'E':
        case 'e': return SEG32_A | SEG32_F | SEG32_G | SEG32_E | SEG32_D;
        case 'F':
        case 'f': return SEG32_A | SEG32_F | SEG32_G | SEG32_E;
        case '-': return SEG32_G;
        default:  return 0x00;
    }
}

void oled_write_7seg32_char(uint8_t x, uint8_t y, char c) {
    uint8_t mask = get_seg_mask(c);
    char buffer[OLED_7SEG32_BYTES];
    memset(buffer, 0, sizeof(buffer));

    // マスクに従って各セグメントデータをOR合成
    for (uint8_t i = 0; i < 7; i++) {
        if (mask & (1 << i)) {
            const unsigned char* seg_ptr = (const unsigned char*)pgm_read_ptr(&seg7_32_allArray[i]);
            for (uint16_t b = 0; b < OLED_7SEG32_BYTES; b++) {
                buffer[b] |= pgm_read_byte(&seg_ptr[b]);
            }
        }
    }

    // OLED画面の指定位置へ書き込み
    for (uint8_t page = 0; page < 4; page++) {
        oled_set_cursor(x / 6, (y / 8) + page);
        oled_write_raw(&buffer[page * OLED_7SEG32_WIDTH], OLED_7SEG32_WIDTH);
    }
}

void oled_write_7seg32_num(uint8_t x, uint8_t y, uint8_t num) {
    if (num > 9) {
        num = 9;
    }
    oled_write_7seg32_char(x, y, '0' + num);
}